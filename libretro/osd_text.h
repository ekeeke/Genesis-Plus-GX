static void osd_fill(uint16_t *frame, int pitch, int width, int height,
      int x, int y, int w, int h, uint16_t color)
{
   int i, j;
   for (j = y; j < y + h; j++)
   {
      if (j < 0 || j >= height)
         continue;
      for (i = x; i < x + w; i++)
         if (i >= 0 && i < width)
            frame[j * pitch + i] = color;
   }
}

/* Draws text, white on a black box, with the box's top-left corner at (x, y)
   of a frame of width x height pixels (pitch in pixels). Each font pixel
   takes sx by sy frame pixels. Parts outside the frame are left out. */
static void osd_draw_text(uint16_t *frame, int pitch, int width, int height,
      int x, int y, int sx, int sy, const char *text)
{
   const int len = (int)strlen(text);
   int i;

   osd_fill(frame, pitch, width, height, x, y, (len * 6 + 1) * sx, 9 * sy, 0x0000);

   for (i = 0; i < len; i++)
   {
      const osd_glyph *glyph = NULL;
      unsigned g;
      int row, col;

      for (g = 0; g < sizeof(osd_glyphs) / sizeof(osd_glyphs[0]); g++)
         if (osd_glyphs[g].c == text[i])
            glyph = &osd_glyphs[g];
      if (!glyph)
         continue;

      for (row = 0; row < 7; row++)
         for (col = 0; col < 5; col++)
            if (glyph->rows[row] & (0x10 >> col))
               osd_fill(frame, pitch, width, height,
                     x + (1 + i * 6 + col) * sx, y + (1 + row) * sy, sx, sy, 0xFFFF);
   }
}

